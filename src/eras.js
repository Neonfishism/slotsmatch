const baseById = Object.fromEntries(NINJAS.map(ninja => [ninja.id, ninja]));
const eraById = Object.fromEntries(ERAS.map(era => [era.id, era]));

// 数组按 nin/tai/gen/int/str/spd/sta/seal 排列。逐人逐项估值，不使用阶段统一倍率。
function profile(eraId, [baseId, form, values, tags, specialty, metadata = {}]) {
  const base = baseById[baseId];
  if (!base || values.length !== STAT_KEYS.length) throw new Error(`阶段档案无效：${baseId}@${eraId}`);
  return {
    ...base,
    ...metadata,
    id: `${baseId}@${eraId}`,
    baseCharacterId: baseId,
    eraId,
    eraShort: eraById[eraId].shortName,
    version: `${eraById[eraId].shortName}·${form}`,
    stats: Object.fromEntries(STAT_KEYS.map((key, index) => [key, values[index]])),
    tags: [...tags],
    specialty,
  };
}

